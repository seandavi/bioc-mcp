import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import MiniSearch from 'minisearch';
import type { CapabilityEnv, Deps, FetchFn } from '../../src/core/deps';
import {
  DOCS_FORMAT_VERSION,
  DOCS_INDEX_OPTIONS,
  type DocsInput,
  type DocsInputCommit,
  type DocsRecord,
  type DocsStore,
} from '../../src/docs-index/schema';
import { createMemoryCache } from '../../src/upstreams/cache';
import { fetchUpstream, fetchUpstreamJson, pathSegment, type Upstream, type UpstreamResponse } from '../../src/upstreams/http';
import { branchCommit, pagesCommit } from './commits';
import type { DocsSourcesConfig } from './config';
import { markdownRecords } from './markdown';
import { siteRecords, siteSubsections, splitSiteRecords, type SiteSubsection } from './site';

export interface DocsBuildDeps {
  fetch: FetchFn;
  now: () => Date;
  buildCommit: string | null;
  env: CapabilityEnv; // GITHUB_TOKEN, when set, goes to the GitHub API requests only
}
export interface DocsIndexArtifact {
  store: DocsStore;
  storeJson: string;
  indexJson: string;
}
export interface RenderedArtifact {
  js: string;
  dts: string;
  bytes: number; // UTF-8 length of js
}

function inputFor(response: UpstreamResponse, recordCount: number, commit: DocsInputCommit | null): DocsInput {
  return {
    url: response.url,
    record_count: recordCount,
    last_modified: response.lastModified,
    fetched_at: response.fetchedAt,
    sha256: createHash('sha256').update(response.body, 'utf8').digest('hex'),
    commit,
  };
}

/** Fetch every input, build records, index them. Any failure throws; there is no partial build. */
export async function buildDocsIndex(config: DocsSourcesConfig, deps: DocsBuildDeps): Promise<DocsIndexArtifact> {
  const docsSite: Upstream = {
    id: 'docs-site',
    name: 'Bioconductor infrastructure docs site',
    baseUrl: config.site_url,
    ttlSeconds: 3600,
    timeoutMs: 30_000,
    description: 'Quarto search.json and page HTML of the infrastructure docs site.',
  };
  const githubRaw: Upstream = {
    id: 'github-raw',
    name: 'GitHub raw files',
    baseUrl: `https://raw.githubusercontent.com/${config.github_owner}/`,
    ttlSeconds: 3600,
    timeoutMs: 30_000,
    description: 'Component docs in the bioc-* repos.',
  };
  const fetchDeps: Deps = { fetch: deps.fetch, cache: createMemoryCache(deps.now), now: deps.now, env: deps.env };

  const inputs: DocsInput[] = [];
  const records: DocsRecord[] = [];
  const add = (response: UpstreamResponse, inputRecords: DocsRecord[], commit: DocsInputCommit | null) => {
    inputs.push(inputFor(response, inputRecords.length, commit));
    records.push(...inputRecords);
  };

  const site = await fetchUpstreamJson(fetchDeps, docsSite, 'search.json');
  const siteCommit = await pagesCommit(fetchDeps, config.site_repo);
  const flat = siteRecords(site.json, config.site_url);
  // Page HTML is read only for h3 structure; the text and provenance stay search.json's (no meta.inputs entry).
  const subsectionsByPage = new Map<string, Map<string, SiteSubsection[]>>();
  for (const record of flat) {
    const page = record.id.slice('site:'.length).split('#')[0]!;
    if (subsectionsByPage.has(page)) continue;
    const response = await fetchUpstream(fetchDeps, docsSite, page.split('/').map(pathSegment).join('/'));
    subsectionsByPage.set(page, siteSubsections(response.body));
  }
  add(site.response, splitSiteRecords(flat, subsectionsByPage, config.site_url), siteCommit);

  for (const { repo, ref, files } of config.repos) {
    const commit = await branchCommit(fetchDeps, repo, ref);
    for (const file of files) {
      const path = [repo, ref, ...file.split('/')].map(pathSegment).join('/');
      const response = await fetchUpstream(fetchDeps, githubRaw, path);
      add(response, markdownRecords({ owner: config.github_owner, repo, ref, file, markdown: response.body }), commit);
    }
  }

  const seen = new Set<string>();
  for (const record of records) {
    if (seen.has(record.id)) throw new Error(`Duplicate docs record id: ${record.id}`);
    seen.add(record.id);
  }

  const store: DocsStore = {
    format_version: DOCS_FORMAT_VERSION,
    meta: {
      built_at: deps.now().toISOString(),
      build_commit: deps.buildCommit,
      record_count: records.length,
      inputs,
    },
    records,
  };
  const miniSearch = new MiniSearch<DocsRecord>(DOCS_INDEX_OPTIONS);
  miniSearch.addAll(records);
  return { store, storeJson: JSON.stringify(store), indexJson: JSON.stringify(miniSearch) };
}

export function renderArtifactModule(artifact: DocsIndexArtifact): RenderedArtifact {
  const js = [
    '// Generated by scripts/build-docs-index.ts from docs-sources.yaml. Do not edit.',
    `export const DOCS_STORE_JSON = ${JSON.stringify(artifact.storeJson)};`,
    `export const DOCS_INDEX_JSON = ${JSON.stringify(artifact.indexJson)};`,
    '',
  ].join('\n');
  const dts = [
    '// Generated by scripts/build-docs-index.ts. Do not edit.',
    'export declare const DOCS_STORE_JSON: string;',
    'export declare const DOCS_INDEX_JSON: string;',
    '',
  ].join('\n');
  return { js, dts, bytes: Buffer.byteLength(js, 'utf8') };
}

/**
 * Throws before writing anything if rendered.bytes > maxBytes. Otherwise mkdir -p outDir and write
 * docs-index.js and docs-index.d.ts.
 */
export async function writeArtifactModule(outDir: string, rendered: RenderedArtifact, maxBytes: number): Promise<void> {
  if (rendered.bytes > maxBytes) {
    throw new Error(
      `docs index module is ${rendered.bytes} bytes; the limit is ${maxBytes} (max_artifact_bytes in ` +
        'docs-sources.yaml). Trim the corpus, or raise the limit after checking the Worker bundle with npm run build.',
    );
  }
  await mkdir(outDir, { recursive: true });
  await writeFile(join(outDir, 'docs-index.js'), rendered.js);
  await writeFile(join(outDir, 'docs-index.d.ts'), rendered.dts);
}
